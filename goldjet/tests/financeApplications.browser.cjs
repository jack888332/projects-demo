    await shot('01-payment-readonly.png', 1440)
    await role('空运客服 · 周倩')
    await route('/finance/reconciliation?tab=pending&direction=应收')
    const source = page.locator('[aria-label="对账明细"] .el-table__row').filter({ hasText: '1,200.00' })
    await source.locator('.el-checkbox').click()
