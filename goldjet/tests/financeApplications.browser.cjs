    await page.getByRole('button', { name: '返回列表', exact: true }).first().click()
    await tab('待收款申请列表')
    await page.getByRole('button', { name: '按查询条件创建', exact: true }).click()
    await expect(amount).toHaveValue('600')
    await page.getByRole('button', { name: '保存申请', exact: true }).click(); await confirm()
    await tab('收款申请列表')
    await application('RA26090800002').getByRole('button', { name: '删除', exact: true }).click(); await confirm()
