    await route('/finance/payment-requests?kind=receipt&tab=pending')
    await expect(lines()).toHaveCount(1)
    await lines().locator('.el-checkbox').click()
    await page.getByRole('button', { name: '按勾选创建', exact: true }).click()
    await expect(page.getByRole('heading', { name: '新建收款申请', exact: true })).toBeVisible()
    const amount = page.getByRole('textbox', { name: '本次申请金额 COST-24-DEMO-1', exact: true })
    await amount.fill('0')
    await page.getByRole('button', { name: '保存申请', exact: true }).click()
    await expect(page.getByText('零金额能否保存存在冲突（202），请填写大于0的金额', { exact: true })).toBeVisible()
    await amount.fill('1201'); await expect(page.getByText('本次申请金额不得大于可申请金额', { exact: true })).toBeVisible()
    await amount.fill('600')
    await select('收款账号', '00000010001 演示银行甲 合成公司甲基本户')
    await expect(page.getByRole('button', { name: '保存并提交', exact: true })).toBeDisabled()
    await page.getByRole('button', { name: '保存收款账户', exact: true }).click()
    await expect(page.locator('dd').filter({ hasText: /^演示银行甲$/ })).toBeVisible()
    await page.getByRole('textbox', { name: '申请备注', exact: true }).fill('=合成,"备注"\n第二行')
    const bytes = Buffer.from('chapter25 attachment\nsynthetic proof\n')
    await page.getByLabel('选择申请附件', { exact: true }).setInputFiles({ name: 'receipt-proof.txt', mimeType: 'text/plain', buffer: bytes })
    await expect(page.getByText(/receipt-proof.txt/)).toBeVisible()
    await page.getByLabel('选择申请附件', { exact: true }).setInputFiles({ name: 'rejected.html', mimeType: 'text/html', buffer: Buffer.from('<p>rejected</p>') })
    await expect(page.getByText(/其他文档格式待确认（206）/)).toBeVisible()
    await page.getByRole('button', { name: '返回列表', exact: true }).first().click()
    await page.locator('.el-message-box').getByRole('button', { name: '取消', exact: true }).click()
    await expect(amount).toHaveValue('600')
    await shot('02-receipt-draft-tablet.png', 820)
    await shot('03-receipt-draft-mobile.png', 390)
    await amount.scrollIntoViewIfNeeded()
    await expect(amount).toBeInViewport()
    const amountBox = await amount.boundingBox()
    expect(amountBox.x).toBeGreaterThanOrEqual(0); expect(amountBox.x + amountBox.width).toBeLessThanOrEqual(390)
    await amount.fill('650'); await expect(page.getByLabel('申请合计')).toContainText('650.00')
    await amount.fill('600')
