    expect(csv.charCodeAt(0)).toBe(0xFEFF); expect(csv).toContain('"RA26090800001"'); expect(csv).not.toContain('RA26090800002')
    expect(csv).toContain('"\'=合成,""备注""\n第二行"'); expect(csv).toContain('"33.96"')
    await page.getByRole('textbox', { name: '查询申请批次号', exact: true }).fill('no-match')
    await expect(rows()).toHaveCount(1)
    await page.getByRole('button', { name: '查询', exact: true }).click(); await expect(rows()).toHaveCount(0)
    await page.getByRole('button', { name: '重置', exact: true }).click(); await expect(rows()).toHaveCount(1)
