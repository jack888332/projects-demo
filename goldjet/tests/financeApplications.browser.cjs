const { chromium, expect } = require(process.env.PLAYWRIGHT_TEST_PATH || 'playwright/test')
const { mkdirSync, readFileSync } = require('node:fs')
const { join } = require('node:path')
const output = join(process.cwd(), 'test-results', 'chapter25')
mkdirSync(output, { recursive: true })

